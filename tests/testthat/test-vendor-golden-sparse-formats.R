# Vendor-upgrade safety net: golden values across sparse-matrix formats for
# solver types that test-sparse-dense-equivalence.R does NOT cover (that
# file is type 0 only, and never pins a golden value -- it just compares
# sparse-vs-dense trained fresh in the same run, so a regression shared by
# both paths would pass it silently). This file is breadth-first by design:
# it exists to give the upcoming LIBLINEAR ~v2.1 -> v2.50 vendor upgrade
# (src/linear.cpp, src/tron.cpp -> newton.cpp, trainLinear.c,
# predictLinear.c) something concrete to diff against, per solver type, per
# accepted sparse-matrix class.
#
# Provenance of tests/testthat/fixtures/vendor-golden-sparse-formats.rds:
# generated by tests/testthat/fixtures/generate-vendor-golden-sparse-formats.R
# from LiblineaR 2.10-26 / vendored LIBLINEAR ~v2.1, a verified-correct build
# (888 pre-existing testthat assertions passing at capture time). It is a
# regression baseline, not externally-audited ground truth. Regenerate
# deliberately (never silently, never as part of routine test runs) by
# re-running that script, ONLY when a reviewed vendor-upgrade stage is meant
# to change these values.
#
# Tolerance: at generation time, max|W_sparse - W_dense| was exactly 0 for
# every (type, sparse class) pair checked here (see the generator's
# sanity-check step, which would have aborted the fixture write otherwise).
# 1e-6 below is therefore generous headroom for a legitimate, tiny,
# solver-internal floating-point ordering difference between formats -- not
# a tolerance tuned to just barely pass -- while still catching any real
# divergence, which upstream regressions or vendor-upgrade mistakes produce
# at far larger magnitudes (see test-solver-equivalence.R's cross-solver
# tolerances of 1e-2 to 1e-3 for a sense of scale).

golden <- readRDS(test_path("fixtures", "vendor-golden-sparse-formats.rds"))

SEED <- 42L

sparse_variants_of <- function(x) {
  list(
    matrix.csr = SparseM::as.matrix.csr(x),
    matrix.csc = SparseM::as.matrix.csc(x),
    matrix.coo = SparseM::as.matrix.coo(x),
    dgCMatrix  = as(x, "dgCMatrix"),
    # dgRMatrix via the CsparseMatrix->RsparseMatrix route, which is not
    # deprecated (unlike as(<matrix>,"dgRMatrix") directly) -- same idiom as
    # test-sparse-dense-equivalence.R.
    dgRMatrix  = as(as(x, "CsparseMatrix"), "RsparseMatrix"),
    dgTMatrix  = as(x, "TsparseMatrix")
  )
}

run_type_check <- function(x, y, type, ref, extra = list()) {
  # (1) Dense path: catches a regression in trainLinear.c/linear.cpp's
  # dense-matrix code path for this specific solver type, independent of
  # anything sparse-related.
  set.seed(SEED)
  dense <- do.call(LiblineaR, c(list(data = x, target = y, type = type, cost = 1), extra))
  expect_equal(unname(dense$W), ref$W_dense, tolerance = 1e-6,
               label = paste("type", type, "dense W"))

  # (2) Every accepted sparse-matrix class, trained fresh, must reproduce
  # the SAME frozen dense W -- catches a regression specific to one sparse
  # class's index-conversion code path (R/LiblineaR.R's per-class dispatch),
  # and, because the reference is the pinned dense value rather than a
  # same-run dense retrain, also re-catches a dense-path regression that
  # happened to move both dense and sparse together.
  variants <- sparse_variants_of(x)
  for (cls in names(variants)) {
    set.seed(SEED)
    m <- suppressMessages(suppressWarnings(
      do.call(LiblineaR, c(list(data = variants[[cls]], target = y, type = type, cost = 1), extra))
    ))
    expect_equal(unname(m$W), ref$W_dense, tolerance = 1e-6,
                 label = paste("type", type, cls, "W"))
  }

  # (3) predict() output from the representative sparse class pinned at
  # generation time -- catches a predictLinear.c sparse-path regression
  # specifically (trainLinear.c producing a correct W does not guarantee
  # predictLinear.c consumes a sparse newdata matrix correctly).
  set.seed(SEED)
  predict_model <- suppressMessages(suppressWarnings(
    do.call(LiblineaR, c(list(data = variants[[ref$predict_class]], target = y, type = type, cost = 1), extra))
  ))
  logistic <- !is.null(ref$probabilities)
  p <- suppressMessages(suppressWarnings(
    if (logistic) {
      predict(predict_model, variants[[ref$predict_class]], proba = TRUE)
    } else {
      predict(predict_model, variants[[ref$predict_class]])
    }
  ))

  if (is.factor(ref$predictions)) {
    expect_equal(as.character(p$predictions), as.character(ref$predictions),
                 label = paste("type", type, ref$predict_class, "predictions"))
  } else {
    expect_equal(unname(p$predictions), unname(ref$predictions), tolerance = 1e-6,
                 label = paste("type", type, ref$predict_class, "predictions"))
  }

  if (logistic) {
    expect_equal(unname(p$probabilities), unname(ref$probabilities), tolerance = 1e-6,
                 label = paste("type", type, ref$predict_class, "probabilities"))
  }
}

test_that("type 0 (L2-reg LR, primal): dense W, all 6 sparse classes, and sparse predict+proba match golden", {
  # Risk: a v2.50 Newton-solver rewrite (or any dense/sparse dispatch change)
  # silently shifting converged coefficients or the predictLinear.c
  # probability computation for the package's headline logistic type.
  skip_if_not_installed("SparseM")
  skip_if_not_installed("Matrix")

  f <- fixture_classif()
  run_type_check(f$x, f$y, type = 0, ref = golden$classif$type0)
})

test_that("type 1 (L2-loss SVC, dual): dense W, all 6 sparse classes, and sparse predictions match golden", {
  # Risk: dual coordinate-descent solvers route randomness through R's own
  # RNG (rand_between() in src/linear.cpp) -- a vendor-upgrade change to the
  # active-set shrinking loop or its random-permutation logic would move
  # these values even under a fixed seed, and only a sparse-specific bug
  # would move the sparse classes without moving dense.
  skip_if_not_installed("SparseM")
  skip_if_not_installed("Matrix")

  f <- fixture_classif()
  run_type_check(f$x, f$y, type = 1, ref = golden$classif$type1)
})

