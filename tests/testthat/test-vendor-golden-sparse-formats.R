test_that("type 6 (L1-reg LR, primal, coordinate descent): dense W, all 6 sparse classes, and sparse predict+proba match golden", {
  # Risk: L1 regularization's coordinate-descent solver (a different
  # optimizer entirely from type 0's Newton method) commonly drives some
  # coefficients exactly to zero (see W_dense[4]==0 in the fixture) --
  # a vendor-upgrade regression could show up as those zeros shifting away
  # from zero, or as a sparse-specific feature-index bug corrupting exactly
  # the zeroed coefficients while non-sparse coefficients look fine.
  skip_if_not_installed("SparseM")
  skip_if_not_installed("Matrix")

  f <- fixture_classif()
  run_type_check(f$x, f$y, type = 6, ref = golden$classif$type6)
})

test_that("type 11 (L2-loss SVR, primal): dense W, all 6 sparse classes, and sparse predictions match golden", {
  # Risk: SVR's primal Newton-type solver is exactly the code path being
  # replaced by the v2.40 Newton-solver rewrite (tron.cpp -> newton.cpp) --
  # this is the canonical "value is EXPECTED to move, but only by the
  # documented amount, and identically for dense and every sparse class"
  # scenario this whole fixture exists to distinguish from a regression.
  skip_if_not_installed("SparseM")
  skip_if_not_installed("Matrix")

  fr <- fixture_regr()
  run_type_check(fr$x, fr$y, type = 11, ref = golden$regr$type11, extra = list(svr_eps = 0.01))
})

